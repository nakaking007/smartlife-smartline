function normalizeTopic(value) {
  const text = String(value || '').trim().toLowerCase();
  if (/ด่วน|ฉุกเฉิน|ตำรวจ|ไฟไหม้|ดับเพลิง|ภัยพิบัติ|ปภ|ชีวิต/.test(text)) return 'urgent';
  if (/มูลนิธิ|กู้ภัย|ช่วยเหลือ|สังคม|ผู้สูงอายุ|เด็ก|คนพิการ|ครอบครัว/.test(text)) return 'rescue';
  if (/สุขภาพ|หมอ|แพทย์|รักษา|โรค|จิต|วัคซีน|สิทธิ/.test(text)) return 'health';
  if (/เดินทาง|ถนน|จราจร|ท่องเที่ยว|ทางหลวง|ขนส่ง/.test(text)) return 'travel';
  if (/ออนไลน์|โกง|หลอก|ไซเบอร์|ร้องเรียน|ผู้บริโภค/.test(text)) return 'online';
  return 'all';
}

function buildEmergencyServicesText(topic = 'all') {
  const normalizedTopic = normalizeTopic(topic);
  const groups = normalizedTopic === 'all'
    ? EMERGENCY_SERVICE_GROUPS
    : EMERGENCY_SERVICE_GROUPS.filter(group => group.topic === normalizedTopic);

  return [
    'บริการฉุกเฉินและเบอร์ช่วยเหลือประชาชน',
    '',
    ...groups.flatMap(group => [
      group.title,
      ...group.items.map(item => `- ${item}`),
      ''
    ]),
    'หมายเหตุ:',
    ...EMERGENCY_SOURCE_LINES.map(item => `- ${item}`),
    '',
    'คำสั่งที่ใช้ได้: /บริการฉุกเฉิน, /เบอร์ฉุกเฉิน, /สุขภาพ, /มูลนิธิ, /เดินทาง, /ปลอดภัยออนไลน์'
  ].join('\n').trim();
}

function buildFreeServicesText(topic = 'all') {
  return buildEmergencyServicesText(topic);
}

function getPaymentLines() {
  const lines = [];

  if (config.paymentPromptPay) {
    lines.push(`พร้อมเพย์: ${config.paymentPromptPay}`);
  }

  if (config.paymentBankAccount) {
    lines.push(`บัญชีโอน: ${config.paymentBankAccount}`);
  }

  if (config.paymentQrUrl) {
    lines.push(`QR/ลิงก์จ่ายเงิน: ${config.paymentQrUrl}`);
  }

  if (config.paymentInstructions) {
    lines.push(`วิธีแจ้งจ่าย: ${config.paymentInstructions}`);
  }

  if (!lines.length) {
    lines.push('ยังไม่ได้ตั้งค่าเลขบัญชี/พร้อมเพย์/QR ใน .env จึงยังไม่แสดงข้อมูลโอนจริง เพื่อไม่ใส่ข้อมูลปลอม');
    lines.push('ตั้งค่า PAYMENT_PROMPTPAY, PAYMENT_BANK_ACCOUNT, PAYMENT_QR_URL หรือ PAYMENT_INSTRUCTIONS แล้วรีสตาร์ตระบบได้ทันที');
  }

  return lines;
}

