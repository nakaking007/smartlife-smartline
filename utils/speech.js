// utils/speech.js
function createSpeechDraft(eventName) {
  const name = String(eventName || '').trim();

  if (!name) {
    throw new Error('Event name is required');
  }

  return [
    `คำกล่าวสำหรับพิธี${name}`,
    "",
    "เรียน ท่านประธานในพิธี แขกผู้มีเกียรติ และผู้เข้าร่วมงานทุกท่าน",
    "",
    `กระผม/ดิฉันมีความยินดีและรู้สึกเป็นเกียรติอย่างยิ่งที่ได้มากล่าวในพิธี${name}ในวันนี้ งานครั้งนี้นับเป็นโอกาสสำคัญที่ทุกท่านได้มาร่วมแสดงความตั้งใจ ความร่วมมือ และความปรารถนาดีต่อกัน`,
    "",
    `พิธี${name}มิได้เป็นเพียงกิจกรรมหนึ่งเท่านั้น แต่ยังสะท้อนถึงความร่วมแรงร่วมใจ ความรับผิดชอบ และคุณค่าที่ทุกฝ่ายให้ความสำคัญ กระผม/ดิฉันขอชื่นชมทุกท่านที่มีส่วนร่วมในการจัดงานครั้งนี้ให้สำเร็จลุล่วงด้วยดี`,
    "",
    "ขออำนวยพรให้การดำเนินงานในวันนี้เป็นไปด้วยความเรียบร้อย เกิดประโยชน์สูงสุด และเป็นจุดเริ่มต้นของสิ่งที่ดีงามต่อไป",
    "",
    "ขอบพระคุณค่ะ/ครับ"
  ].join("\n");
}

module.exports = { createSpeechDraft };
