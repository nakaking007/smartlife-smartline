function getRiskLevel(score) {
  if (score >= 70) return 'เสี่ยงสูงมาก';
  if (score >= 45) return 'เสี่ยงสูง';
  if (score >= 25) return 'น่าสงสัย';
  return 'ยังไม่พบสัญญาณเสี่ยงชัดเจน';
}

function checkScam(text) {
  const message = String(text || '').trim();
  const hits = RULES.filter(rule => rule.pattern.test(message));
  const score = Math.min(100, hits.reduce((sum, rule) => sum + rule.weight, 0));
  const level = getRiskLevel(score);

  if (!message) {
    return 'พิมพ์ /เช็คโกง ตามด้วยข้อความ SMS/LINE ที่สงสัย เช่น /เช็คโกง คุณได้รับเงินคืน กดลิงก์นี้';
  }

  const advice = hits.length
    ? hits.map(rule => `- ${rule.label}: ${rule.advice}`)
    : ['- ยังไม่พบคำเสี่ยงเด่น แต่ถ้ามีลิงก์/การโอนเงิน/การขอรหัส ให้ตรวจสอบจากแหล่งทางการก่อน'];

  return [
    'ผลเช็คข้อความเสี่ยงโกง',
    `ระดับ: ${level} (${score}/100)`,
    '',
    'สัญญาณที่พบ:',
    ...advice,
    '',
    'ทางเลือกที่ปลอดภัย:',
    '- โทรเช็กจากเบอร์ทางการของธนาคาร/หน่วยงานเอง',
    '- ไม่ส่ง OTP, PIN, รหัสผ่าน, เลขบัตร หรือภาพบัตรประชาชนในแชต',
    '- หากเสียเงินแล้ว ให้เก็บหลักฐานและติดต่อธนาคาร/ตำรวจไซเบอร์หรือสายด่วนที่เกี่ยวข้อง'
  ].join('\n');
}

